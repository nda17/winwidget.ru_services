export function mainFrontendTarget(rawUrl) {
	assert.ok(
		typeof rawUrl === 'string' &&
			rawUrl.startsWith('/') &&
			!rawUrl.startsWith('//') &&
			!/[\\\u0000-\u0020]/.test(rawUrl),
		'Invalid local proxy path'
	);
	const decoded = decodeURIComponent(
		new URL(rawUrl, 'http://localhost:3000').pathname
	);
	assert.ok(
		!/[\\\u0000-\u001f]/.test(decoded),
		'Invalid local proxy path'
	);
	const pathname = posix.normalize(decoded);
	const asset =
		/^\/_frontends\/(landing|widgets|admin-panel)\/_next\//.exec(pathname);
	if (asset) return asset[1];
	if (pathname.startsWith('/_frontends/')) return null;
	const segment = pathname.split('/')[1];
	if (segment === 'admin') return 'admin-panel';
	return WIDGET_PREFIXES.has(segment) ? 'widgets' : 'landing';
}
export function createFrontendProxyHandlers({
	request = httpRequest
} = {}) {
	const connections = new Set();
	const target = (req, res) => {
		try {
			return mainFrontendTarget(req.url);
		} catch {
			if (res) res.writeHead(400).end();
			else req.socket?.destroy();
			return undefined;
		}
	};
	return {
		connections,
		http(req, res) {
			const app = target(req, res);
			if (app === undefined) return;
			if (app === null) {
				res.writeHead(404).end();
				return;
			}
			const upstream = request(
				{
					hostname: '127.0.0.1',
					port: FRONTEND_PORTS[app],
					method: req.method,
					path: req.url,
					headers: { ...req.headers, host: 'localhost:3000' }
				},
				response => {
					res.writeHead(response.statusCode || 502, response.headers);
					response.pipe(res);
				}
			);
			upstream.on('error', () => {
				if (!res.headersSent) res.writeHead(502);
				res.end();
			});
			upstream.setTimeout(120000, () => upstream.destroy());
			req.on('aborted', () => upstream.destroy());
			res.on('close', () => upstream.destroy());
			req.pipe(upstream);
		},
		upgrade(req, socket, head) {
			const app = target(req);
			if (!app) {
				socket.destroy();
				return;
			}
			const upstream = request({
				hostname: '127.0.0.1',
				port: FRONTEND_PORTS[app],
				method: req.method,
				path: req.url,
				headers: { ...req.headers, host: 'localhost:3000' }
			});
			upstream.on('upgrade', (response, peer, upstreamHead) => {
				connections.add(peer);
				peer.once('close', () => connections.delete(peer));
				socket.write(
					`HTTP/1.1 ${response.statusCode} ${response.statusMessage}\r\n${response.rawHeaders.reduce((lines, value, index, all) => (index % 2 === 0 ? [...lines, `${value}: ${all[index + 1]}`] : lines), []).join('\r\n')}\r\n\r\n`
				);
				if (head.length) peer.write(head);
				if (upstreamHead.length) socket.write(upstreamHead);
				peer.on('error', () => socket.destroy());
				socket.on('error', () => peer.destroy());
				socket.on('close', () => peer.destroy());
				peer.pipe(socket).pipe(peer);
			});
			upstream.on('response', response => {
				response.resume();
				socket.destroy();
			});
			upstream.on('error', () => socket.destroy());
			upstream.setTimeout(10000, () => upstream.destroy());
			upstream.end();
		}
	};
}
export async function startFrontendProxy() {
	const handlers = createFrontendProxyHandlers();
	const server = createServer(handlers.http);
	server.on('connection', socket => {
		handlers.connections.add(socket);
		socket.once('close', () => handlers.connections.delete(socket));
	});
	server.on('upgrade', handlers.upgrade);
	await new Promise((resolveStarted, reject) => {
		server.once('error', reject);
		server.listen(3000, '127.0.0.1', resolveStarted);
	});
	return {
		close: () =>
			new Promise(resolveClosed => {
				server.close(resolveClosed);
				for (const connection of handlers.connections)
					connection.destroy();
				server.closeAllConnections();
			})
	};
}

export async function checkFrontendReadiness(port, app) {
	assert.equal(FRONTEND_PORTS[app], port);
	const response = await fetch(
		`http://127.0.0.1:${port}/__frontend/health`,
		{ redirect: 'error', signal: AbortSignal.timeout(3000) }
	);
	assert.equal(response.status, 200);
	assert.equal(response.headers.get('cache-control'), 'no-store');
	const reader = response.body.getReader();
	const chunks = [];
	let bytes = 0;
	try {
		for (;;) {
			const { done, value } = await reader.read();
			if (done) break;
			bytes += value.byteLength;
			assert.ok(
				bytes <= 512,
				'Frontend readiness response exceeds its bound'
			);
			chunks.push(Buffer.from(value));
		}
	} finally {
		await reader.cancel();
	}
	const text = Buffer.concat(chunks).toString('utf8');
	assert.deepEqual(JSON.parse(text), {
		status: 'ok',
		application: app,
		revision: FRONTEND_REVISION
	});
}
