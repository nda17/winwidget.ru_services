export const FRONTEND_PORTS = Object.freeze({
	landing: 3100,
	widgets: 3002,
	'admin-panel': 3003,
	crm: 3001
});
export const FRONTEND_REVISION = 'f'.repeat(40);
const ROOT_FILES = [
	'package.json',
	'pnpm-workspace.yaml',
	'pnpm-lock.yaml',
	'next.config.mjs',
	'tsconfig.base.json',
	'tailwind.config.ts',
	'postcss.config.js'
];
const HASH = /^[a-f0-9]{64}$/;
const digest = value => createHash('sha256').update(value).digest('hex');
const forbidden = name =>
	name.startsWith('.env') ||
	[
		'.git',
		'.next',
		'node_modules',
		'TEMP',
		'other_files',
		'next-env.d.ts'
	].includes(name) ||
	name.endsWith('.tsbuildinfo');
const exists = async path => {
	try {
		return await lstat(path);
	} catch (error) {
		if (error.code === 'ENOENT') return null;
		throw error;
	}
};
const safeRelative = value => {
	assert.equal(typeof value, 'string');
	assert.ok(
		value.length > 0 &&
			value.length < 2048 &&
			!/[\\\u0000-\u001f]/.test(value)
	);
	assert.ok(
		value
			.split('/')
			.every(
				part => part && part !== '.' && part !== '..' && !forbidden(part)
			)
	);
	return value;
};
async function directory(path) {
	const info = await lstat(path);
	assert.ok(
		info.isDirectory() && !info.isSymbolicLink(),
		'Frontend directories cannot be symlinks'
	);
}
async function parents(root, file, create = false) {
	let current = root;
	for (const part of safeRelative(file).split('/').slice(0, -1)) {
		current = join(current, part);
		if (create)
			await mkdir(current, { recursive: false, mode: 0o700 }).catch(
				error => {
					if (error.code !== 'EEXIST') throw error;
				}
			);
		await directory(current);
	}
}
async function packageName(root, file) {
	await parents(root, file);
	const info = await lstat(join(root, file));
	assert.ok(
		info.isFile() && !info.isSymbolicLink() && info.size <= 1024 * 1024,
		'Invalid frontend package manifest'
	);
	try {
		return JSON.parse(await readFile(join(root, file), 'utf8')).name;
	} catch {
		throw new Error('Invalid frontend package manifest');
	}
}

export async function resolveFrontendSource(workspaceRoot, explicit) {
	const workspace = await realpath(workspaceRoot);
	const source = resolve(
		explicit || join(workspace, 'winwidget.ru_client')
	);
	assert.equal(
		dirname(source),
		workspace,
		'Frontend source must be an immediate workspace child'
	);
	assert.ok(
		['winwidget.ru_client', 'winwidget.ru_frontends'].includes(
			basename(source)
		),
		'Only the frontend monorepo is supported'
	);
	await directory(source);
	assert.equal(await realpath(source), source);
	assert.equal(
		await packageName(source, 'package.json'),
		'winwidget-frontends'
	);
	for (const app of Object.keys(FRONTEND_PORTS)) {
		await directory(join(source, 'apps'));
		await directory(join(source, 'apps', app));
		const expected = app === 'crm' ? 'wincrm-client' : `@winwidget/${app}`;
		assert.equal(
			await packageName(source, `apps/${app}/package.json`),
			expected
		);
	}
	return source;
}

async function roots(root) {
	await directory(join(root, 'packages'));
	const packages = (await readdir(join(root, 'packages'))).sort();
	assert.ok(packages.length > 0 && packages.length <= 32);
	for (const name of packages) assert.match(name, /^[a-z0-9][a-z0-9-]*$/);
	return [
		...ROOT_FILES,
		'scripts',
		'public',
		...Object.keys(FRONTEND_PORTS).map(app => `apps/${app}`),
		...packages.map(name => `packages/${name}`)
	];
}
export async function frontendSnapshot(root) {
	const files = {};
	let bytes = 0;
	const walk = async file => {
		const parts = file.split('/');
		if (parts.some(forbidden)) return;
		// Main public trees are generated by the owned sync-public helper.
		if (parts[0] === 'apps' && parts[2] === 'public' && parts[1] !== 'crm')
			return;
		const path = join(root, safeRelative(file));
		await parents(root, file);
		const info = await exists(path);
		if (!info) return;
		assert.ok(
			!info.isSymbolicLink(),
			'Frontend snapshot cannot follow source symlinks'
		);
		if (info.isDirectory()) {
			for (const name of (await readdir(path)).sort())
				await walk(`${file}/${name}`);
		} else {
			assert.ok(info.isFile() && info.size <= 32 * 1024 * 1024);
			bytes += info.size;
			assert.ok(
				bytes <= 256 * 1024 * 1024 && Object.keys(files).length < 25000,
				'Frontend snapshot is bounded'
			);
			files[file] = digest(await readFile(path));
		}
	};
	for (const file of await roots(root)) await walk(file);
	const ordered = Object.fromEntries(
		Object.entries(files).sort(([a], [b]) => a.localeCompare(b, 'en'))
	);
	return { sourceHash: digest(JSON.stringify(ordered)), files: ordered };
}
async function validateMirror(stateDirectory, mirror) {
	const parent = await realpath(stateDirectory);
	const info = await lstat(parent);
	assert.ok(
		info.uid === process.getuid() && (info.mode & 0o077) === 0,
		'Frontend state must be private and owned'
	);
	assert.equal(mirror, join(parent, 'frontends'));
	await directory(mirror);
	assert.equal(await realpath(mirror), mirror);
}
async function writeSource(root, mirror, file, expectedHash) {
	await parents(root, file);
	const info = await lstat(join(root, file));
	assert.ok(info.isFile() && !info.isSymbolicLink());
	const bytes = await readFile(join(root, file));
	assert.equal(
		digest(bytes),
		expectedHash,
		'Frontend source changed during copy'
	);
	await parents(mirror, file, true);
	const temporary = join(
		dirname(join(mirror, file)),
		`.frontend-copy-${randomUUID()}`
	);
	await writeFile(temporary, bytes, { flag: 'wx', mode: 0o600 });
	await rename(temporary, join(mirror, file));
}
export async function refreshFrontendMirror({
	source,
	mirror,
	stateDirectory,
	previous
}) {
	await validateMirror(stateDirectory, mirror);
	await dependencies(source, mirror);
	assert.ok(
		previous &&
			previous.source === source &&
			previous.mirror === mirror &&
			HASH.test(previous.sourceHash)
	);
	assert.equal(
		digest(JSON.stringify(previous.files)),
		previous.sourceHash,
		'Previous source inventory is invalid'
	);
	for (const [file, hash] of Object.entries(previous.files)) {
		safeRelative(file);
		assert.match(hash, HASH);
	}
	const current = await frontendSnapshot(mirror);
	assert.deepEqual(
		current.files,
		previous.files,
		'Unknown or modified mirror source; restart a fresh harness'
	);
	const next = await frontendSnapshot(source);
	// All ownership and hashes are checked before replacing/removing any source.
	for (const [file, hash] of Object.entries(next.files))
		if (previous.files[file] !== hash)
			await writeSource(source, mirror, file, hash);
	for (const file of Object.keys(previous.files)) {
		if (Object.hasOwn(next.files, file)) continue;
		await parents(mirror, file);
		assert.equal(
			digest(await readFile(join(mirror, file))),
			previous.files[file]
		);
		await unlink(join(mirror, file));
		let parent = dirname(join(mirror, file));
		while (
			parent !== mirror &&
			relative(mirror, parent).split(sep).length > 2
		) {
			try {
				await rmdir(parent);
			} catch (error) {
				if (['ENOTEMPTY', 'ENOENT'].includes(error.code)) break;
				throw error;
			}
			parent = dirname(parent);
		}
	}
	assert.deepEqual(
		(await frontendSnapshot(source)).files,
		next.files,
		'Frontend source changed during refresh'
	);
	assert.deepEqual((await frontendSnapshot(mirror)).files, next.files);
	return { source, mirror, ...next };
}
async function dependencies(source, mirror) {
	const owners = [
		'',
		...Object.keys(FRONTEND_PORTS).map(app => `apps/${app}`),
		...(await readdir(join(source, 'packages'))).map(
			name => `packages/${name}`
		)
	];
	for (const owner of owners) {
		const from = join(source, owner, 'node_modules');
		const to = join(mirror, owner, 'node_modules');
		const installed = await exists(from);
		if (!installed) {
			assert.ok(
				owner.startsWith('packages/'),
				'Install the monorepo dependencies before starting the harness'
			);
			continue;
		}
		assert.ok(
			(await realpath(from)).startsWith(`${source}${sep}`),
			'Dependency links must resolve inside the selected monorepo'
		);
		const linked = await exists(to);
		if (linked)
			assert.ok(
				linked.isSymbolicLink() && (await readlink(to)) === from,
				'Unexpected mirror dependency link'
			);
		else await symlink(from, to, 'dir');
	}
}
export async function prepareFrontendMirror({
	workspaceRoot,
	explicitSource,
	stateDirectory
}) {
	const source = await resolveFrontendSource(
		workspaceRoot,
		explicitSource
	);
	const mirror = join(await realpath(stateDirectory), 'frontends');
	await mkdir(mirror, { mode: 0o700 });
	await validateMirror(stateDirectory, mirror);
	const snapshot = await frontendSnapshot(source);
	for (const [file, hash] of Object.entries(snapshot.files))
		await writeSource(source, mirror, file, hash);
	assert.deepEqual(
		(await frontendSnapshot(source)).files,
		snapshot.files,
		'Frontend changed during copy'
	);
	assert.deepEqual((await frontendSnapshot(mirror)).files, snapshot.files);
	await dependencies(source, mirror);
	return { source, mirror, ...snapshot };
}
export async function syncFrontendPublic(snapshot) {
	const { syncPublic } = await import(
		pathToFileURL(join(snapshot.mirror, 'scripts/sync-public.mjs')).href
	);
	for (const app of ['landing', 'widgets', 'admin-panel'])
		await syncPublic({ root: snapshot.mirror, app });
}
export function frontendProcesses(snapshot) {
	return Object.entries(FRONTEND_PORTS).map(([app, port]) => ({
		label: `frontend-${app}`,
		app,
		port,
		cwd: join(snapshot.mirror, 'apps', app),
		args: [
			join(
				snapshot.mirror,
				'apps',
				app,
				'node_modules/next/dist/bin/next'
			),
			'dev',
			join(snapshot.mirror, 'apps', app),
			'--hostname',
			'127.0.0.1',
			'--port',
			String(port),
			...(app === 'crm' ? ['--webpack'] : [])
		]
	}));
}

